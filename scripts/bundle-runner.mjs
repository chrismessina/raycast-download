/**
 * Bundle the runner into a single self-contained file.
 *
 * WHY THIS EXISTS — the defect it fixes, verified 2026-08-01:
 *
 * `dist/runner.js` is a plain `tsc` output. It `require("./curl")`,
 * `require("./status")`, `require("./paths")`. That is fine inside
 * `node_modules`, where its siblings sit next to it — and completely broken the
 * moment a consumer copies it somewhere else, which is exactly what a bundled
 * Raycast extension must do:
 *
 *     Error: Cannot find module './curl'
 *     Require stack:
 *     - .../extensions/fathom/assets/raycast-downloader-runner.js
 *
 * The runner died on that line every single time, ~8s after spawn, having
 * written no status of its own. The parent saw only "runner vanished without
 * recording an outcome" — an accurate report of a cause it could not see.
 *
 * The subtle part, and the reason path-searching did not fix this: `runnerPath()`
 * FOUND the file. Locating an artifact and that artifact being runnable are
 * different properties, and only the first one was ever tested. A copied `tsc`
 * output is not a shippable artifact.
 *
 * So the package now ships `dist/runner.bundle.js` with its local graph inlined,
 * and consumers copy THAT. One file, no siblings, nothing to get separated from.
 *
 * Written by hand rather than with esbuild deliberately: the runner's local
 * graph is four modules importing nothing but `node:*` builtins, so the bundle
 * is a mechanical inline — and this keeps the package's zero-dependency
 * property true at build time as well as at runtime.
 */

import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const dist = join(root, "dist");
const entry = join(dist, "runner.js");
const outPath = join(dist, "runner.bundle.js");

if (!existsSync(entry)) {
  console.error(`bundle-runner: ${entry} does not exist — run \`tsc\` first.`);
  process.exit(1);
}

/** Relative `require("./x")` calls. Anything else (node:*, @raycast/api) stays external. */
const LOCAL_REQUIRE = /require\((["'])\.\/([A-Za-z0-9_-]+)\1\)/g;

/**
 * Collect the local module graph depth-first, so a module is always emitted
 * after everything it depends on.
 */
const order = [];
const seen = new Set();

function visit(name) {
  if (seen.has(name)) return;
  seen.add(name);

  const file = join(dist, `${name}.js`);
  if (!existsSync(file)) {
    console.error(`bundle-runner: ${file} is required but missing.`);
    process.exit(1);
  }

  const source = readFileSync(file, "utf8");
  for (const match of source.matchAll(LOCAL_REQUIRE)) visit(match[2]);

  order.push({ name, source });
}

const entrySource = readFileSync(entry, "utf8");
for (const match of entrySource.matchAll(LOCAL_REQUIRE)) visit(match[2]);

/**
 * A tiny CommonJS registry. Each module keeps its own `exports` object and is
 * evaluated lazily on first require, which preserves `tsc`'s circular-import
 * semantics rather than assuming there are none.
 */
const rewrite = (source) => source.replace(LOCAL_REQUIRE, "__req__($1$2$1)");

const modules = order
  .map(({ name, source }) => `  ${JSON.stringify(name)}: function (exports, module) {\n${rewrite(source)}\n  },`)
  .join("\n");

const bundle = `#!/usr/bin/env node
// GENERATED by scripts/bundle-runner.mjs — do not edit.
// Self-contained detached download runner. See the script header for why this
// file exists rather than shipping dist/runner.js directly.
"use strict";

var __defs__ = {
${modules}
};
var __cache__ = {};
function __req__(name) {
  var cached = __cache__[name];
  if (cached) return cached.exports;
  var module = { exports: {} };
  __cache__[name] = module;
  __defs__[name](module.exports, module);
  return module.exports;
}

${rewrite(entrySource)}
`;

writeFileSync(outPath, bundle, { mode: 0o755 });

const inlined = order.map((m) => m.name).join(", ");
console.log(`bundle-runner: wrote dist/runner.bundle.js (inlined: ${inlined || "none"})`);
